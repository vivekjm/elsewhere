"""Regenerates src/loom/illustrations.ts from ill.py. Run: python3 scripts/illustrations/export.py"""
import json, pathlib, sys
here = pathlib.Path(__file__).parent
sys.path.insert(0, str(here))
from ill import BY_NAME
from smooth import smooth

out = {}
for name, fn in BY_NAME.items():
    svg = fn("100%", "100%")
    out[name] = smooth(svg).replace('<svg aria-hidden="true" ', '<svg ').replace(' style="display:block;flex:0 0 auto"', '')

body = "// Generated by scripts/illustrations/export.py. Do not edit by hand.\n"
body += "export const illustrations = " + json.dumps(out, indent=2, ensure_ascii=False) + " as const;\n\n"
body += "export type IllustrationName = keyof typeof illustrations;\n"
target = here.parent.parent / "src" / "loom" / "illustrations.ts"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(body)
print(f"wrote {len(out)} illustrations to {target}")
